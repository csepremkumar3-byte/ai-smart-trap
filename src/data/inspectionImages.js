// Helper to get image by trap ID or fallback by index
export const getInspectionImageForTrap = (trapId) => {
  const match = INSPECTION_IMAGES.find((img) => img.trapId === trapId);
  if (match) return match;
  // Deterministic fallback based on trap ID hash
  let sum = 0;
  for (let i = 0; i < (trapId?.length || 0); i++) {
    sum += trapId.charCodeAt(i);
  }
  return INSPECTION_IMAGES[sum % INSPECTION_IMAGES.length];
};
